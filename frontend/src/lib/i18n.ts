export const toBengaliNumber = (num: number | string | undefined | null): string => {
  if (num === undefined || num === null) return '';
  const str = num.toString();
  const bengaliDigits: { [key: string]: string } = {
    '0': '০',
    '1': '১',
    '2': '২',
    '3': '৩',
    '4': '৪',
    '5': '৫',
    '6': '৬',
    '7': '৭',
    '8': '৮',
    '9': '৯',
    '.': '.',
    ',': ',',
  };
  return str.replace(/[0-9]/g, (w) => bengaliDigits[w] || w);
};

export const formatMoney = (amount: number, locale: Locale = 'en', currency = 'BDT'): string => {
  const formatted = new Intl.NumberFormat('en-US', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(Math.round(amount || 0));

  if (locale === 'bn') {
    return `${toBengaliNumber(formatted)} ৳`;
  }
  return `৳ ${formatted}`;
};
